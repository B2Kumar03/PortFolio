/**
 * One-time (or repeatable) Portl screenshot sync.
 * Fetches https://demoscreensort.vercel.app/, downloads screenshots locally,
 * optimizes WebP variants, and generates src/data/portlScreens.js
 *
 * Usage: npm run sync:portl
 */

import { createWriteStream } from 'node:fs'
import { mkdir, writeFile, rm, copyFile } from 'node:fs/promises'
import { pipeline } from 'node:stream/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const GALLERY_URL = 'https://demoscreensort.vercel.app/'
const ASSETS_ROOT = path.join(ROOT, 'src', 'assets', 'projects', 'portl')
const PUBLIC_ROOT = path.join(ROOT, 'public', 'projects', 'portl')
const ORIGINALS_ROOT = path.join(ASSETS_ROOT, '_originals')
const MANIFEST_PATH = path.join(ROOT, 'src', 'data', 'portlScreens.js')
const HERO_PATH = path.join(ROOT, 'src', 'data', 'portlHero.js')

const ROLES = ['resident', 'guard', 'admin']

function encodePath(filePath) {
  return filePath.split('/').map(encodeURIComponent).join('/')
}

function toKebabCase(value) {
  return value
    .replace(/\.[^.]+$/, '')
    .replace(/[_\s]+/g, '-')
    .replace(/[^a-zA-Z0-9-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase()
}

function extractFlows(html) {
  const match = html.match(/const FLOWS = (\{[\s\S]*?\n\s*\});/)
  if (!match) throw new Error('Could not find FLOWS object in gallery HTML')
  // eslint-disable-next-line no-new-func
  return Function(`"use strict"; return (${match[1]});`)()
}

async function fetchText(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`Failed to fetch ${url}: ${res.status}`)
  return res.text()
}

async function downloadFile(url, dest) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`Download failed (${res.status}): ${url}`)
  const type = res.headers.get('content-type') || ''
  if (!type.includes('image')) {
    throw new Error(`Unexpected content-type "${type}" for ${url}`)
  }
  await mkdir(path.dirname(dest), { recursive: true })
  await pipeline(res.body, createWriteStream(dest))
}

async function optimizeImage(inputPath, role, slug) {
  const assetDir = path.join(ASSETS_ROOT, role)
  const publicDir = path.join(PUBLIC_ROOT, role)
  await mkdir(assetDir, { recursive: true })
  await mkdir(publicDir, { recursive: true })

  const mediumName = `${slug}.webp`
  const thumbName = `${slug}-thumb.webp`
  const mediumAsset = path.join(assetDir, mediumName)
  const thumbAsset = path.join(assetDir, thumbName)

  const meta = await sharp(inputPath).metadata()

  await sharp(inputPath)
    .resize({ width: 540, withoutEnlargement: true })
    .webp({ quality: 78 })
    .toFile(mediumAsset)

  await sharp(inputPath)
    .resize({ width: 280, withoutEnlargement: true })
    .webp({ quality: 68 })
    .toFile(thumbAsset)

  await copyFile(mediumAsset, path.join(publicDir, mediumName))
  await copyFile(thumbAsset, path.join(publicDir, thumbName))

  const mediumMeta = await sharp(mediumAsset).metadata()
  const thumbMeta = await sharp(thumbAsset).metadata()

  return {
    mediumName,
    thumbName,
    width: mediumMeta.width || 540,
    height:
      mediumMeta.height ||
      Math.round(540 * ((meta.height || 2412) / (meta.width || 1080))),
    thumbWidth: thumbMeta.width || 280,
    thumbHeight:
      thumbMeta.height ||
      Math.round(280 * ((meta.height || 2412) / (meta.width || 1080))),
  }
}

function buildManifest(screensByRole, stats) {
  return `/**
 * AUTO-GENERATED by scripts/sync-portl-screens.mjs
 * Do not edit by hand. Re-run: npm run sync:portl
 * Generated: ${new Date().toISOString()}
 *
 * Image URLs point at locally synced public assets so the homepage
 * does not import all screenshots into the JS bundle.
 */

export const portlScreenStats = ${JSON.stringify(stats, null, 2)}

export const portlScreens = ${JSON.stringify(screensByRole, null, 2)}

export function getPortlScreen(role, matcher) {
  const list = portlScreens[role] || []
  if (typeof matcher === 'function') return list.find(matcher) || null
  const needle = String(matcher).toLowerCase()
  return (
    list.find((screen) => screen.id === needle) ||
    list.find((screen) => screen.name.toLowerCase() === needle) ||
    list.find((screen) => screen.src.includes(needle)) ||
    null
  )
}

export function getPortlHeroScreens() {
  return {
    resident:
      getPortlScreen('resident', (s) => s.name.toLowerCase() === 'dashboard') ||
      portlScreens.resident[0],
    guard:
      getPortlScreen('guard', (s) => s.name.toLowerCase() === 'dashboard') ||
      portlScreens.guard[0],
    admin:
      getPortlScreen('admin', (s) => s.name.toLowerCase().includes('command')) ||
      portlScreens.admin[0],
  }
}
`
}

function buildHeroModule(hero) {
  return `/**
 * AUTO-GENERATED hero screenshot helpers.
 * Re-run: npm run sync:portl
 */

export const portlHeroScreens = ${JSON.stringify(hero, null, 2)}
`
}

async function main() {
  console.log('Fetching gallery HTML…')
  const html = await fetchText(GALLERY_URL)
  const flows = extractFlows(html)

  await rm(ORIGINALS_ROOT, { recursive: true, force: true })
  await rm(PUBLIC_ROOT, { recursive: true, force: true })
  for (const role of ROLES) {
    await rm(path.join(ASSETS_ROOT, role), { recursive: true, force: true })
    await mkdir(path.join(ASSETS_ROOT, role), { recursive: true })
    await mkdir(path.join(PUBLIC_ROOT, role), { recursive: true })
    await mkdir(path.join(ORIGINALS_ROOT, role), { recursive: true })
  }

  const screensByRole = { resident: [], guard: [], admin: [] }
  const seen = new Set()
  const failures = []
  let downloaded = 0

  for (const role of ROLES) {
    const flow = flows[role]
    if (!flow?.screens?.length) {
      failures.push(`Missing screens for role: ${role}`)
      continue
    }

    for (const screen of flow.screens) {
      const sourceUrl = new URL(encodePath(screen.file), GALLERY_URL).href
      const originalName = path.basename(screen.file)
      const slug = toKebabCase(originalName)
      const dedupeKey = `${role}:${slug}`
      if (seen.has(dedupeKey)) {
        console.log(`Skip duplicate: ${dedupeKey}`)
        continue
      }
      seen.add(dedupeKey)

      const originalPath = path.join(ORIGINALS_ROOT, role, originalName)

      try {
        console.log(`Downloading ${role}/${originalName}`)
        await downloadFile(sourceUrl, originalPath)
        const optimized = await optimizeImage(originalPath, role, slug)
        downloaded += 1

        screensByRole[role].push({
          id: `${role}-${slug}`,
          role,
          name: screen.name,
          group: screen.group,
          alt: `${flow.label} — ${screen.name}`,
          sourceUrl,
          originalFile: screen.file,
          src: `/projects/portl/${role}/${optimized.mediumName}`,
          thumb: `/projects/portl/${role}/${optimized.thumbName}`,
          width: optimized.width,
          height: optimized.height,
          thumbWidth: optimized.thumbWidth,
          thumbHeight: optimized.thumbHeight,
        })
      } catch (error) {
        failures.push(`${role}/${originalName}: ${error.message}`)
        console.error(`FAILED ${role}/${originalName}:`, error.message)
      }
    }
  }

  const stats = {
    source: GALLERY_URL,
    downloaded,
    resident: screensByRole.resident.length,
    guard: screensByRole.guard.length,
    admin: screensByRole.admin.length,
    total:
      screensByRole.resident.length +
      screensByRole.guard.length +
      screensByRole.admin.length,
    failures: failures.length,
  }

  const hero = {
    resident:
      screensByRole.resident.find((s) => s.name.toLowerCase() === 'dashboard') ||
      screensByRole.resident[0],
    guard:
      screensByRole.guard.find((s) => s.name.toLowerCase() === 'dashboard') ||
      screensByRole.guard[0],
    admin:
      screensByRole.admin.find((s) => s.name.toLowerCase().includes('command')) ||
      screensByRole.admin[0],
  }

  await writeFile(MANIFEST_PATH, buildManifest(screensByRole, stats), 'utf8')
  await writeFile(HERO_PATH, buildHeroModule(hero), 'utf8')

  console.log('\nSync complete')
  console.log(JSON.stringify(stats, null, 2))
  if (failures.length) {
    console.log('\nFailed downloads:')
    failures.forEach((item) => console.log(` - ${item}`))
    process.exitCode = 1
  }
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
